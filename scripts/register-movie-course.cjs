/* Publish only a built, reviewed course. Original playback URLs are preserved. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),id=process.argv[2];
assert(/^movie-[a-z0-9-]+$/.test(id||''),'Specify a movie course seriesId');
const dir=path.join(root,'data',id),plan=JSON.parse(fs.readFileSync(path.join(dir,'editorial.json'))),manifest=JSON.parse(fs.readFileSync(path.join(dir,'alignment.json'))),eps=JSON.parse(fs.readFileSync(path.join(dir,'episodes.json')));
assert.equal(plan.seriesId,id);assert(manifest.verification.anchors.length>=3&&eps.length>=4);
const file=path.join(root,`data/movies/${plan.collectionId||'harry-potter'}/movies.json`),catalogue=JSON.parse(fs.readFileSync(file)),movie=catalogue.sources.find(m=>m.id===plan.movieId);
assert(movie);assert.equal(movie.hlsUrl,manifest.originalHlsUrl);
const before=JSON.stringify(catalogue.sources.map(m=>[m.id,m.hlsUrl,m.backupHlsUrl,m.embedUrl]));
movie.studyCourse={seriesId:id,episodeCount:eps.length};
assert.equal(before,JSON.stringify(catalogue.sources.map(m=>[m.id,m.hlsUrl,m.backupHlsUrl,m.embedUrl])));
fs.writeFileSync(file,JSON.stringify(catalogue,null,2)+'\n');
const configFile=path.join(root,'netlify.toml'),config=fs.readFileSync(configFile,'utf8'),headerPath=`/data/${id}/hls/*`;
if(!config.includes(`for = "${headerPath}"`))fs.writeFileSync(configFile,config+`\n[[headers]]\n  for = "${headerPath}"\n  [headers.values]\n    Content-Type = "application/vnd.apple.mpegurl"\n`);
const courses=[];
for(const group of fs.readdirSync(path.join(root,'data/movies'))){
 const movieFile=path.join(root,'data/movies',group,'movies.json');if(!fs.existsSync(movieFile))continue;
 for(const m of JSON.parse(fs.readFileSync(movieFile)).sources||[])if(m.studyCourse){
  const sid=m.studyCourse.seriesId;assert(/^movie-[a-z0-9-]+$/.test(sid));assert(fs.existsSync(path.join(root,'data',sid,'alignment.json')));courses.push(sid);
 }
}
fs.writeFileSync(path.join(root,'netlify/functions/lib/movie-study-catalog.cjs'),'// Generated by scripts/register-movie-course.cjs. Only reviewed courses.\nmodule.exports={\n'+courses.map(sid=>`  '${sid}':require('../../../data/${sid}/alignment.json')`).join(',\n')+'\n};\n');
console.log(`Registered ${id}; ${courses.length} reviewed courses; original sources unchanged.`);
